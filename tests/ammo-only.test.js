'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),cp=require('node:child_process'),path=require('node:path');
const plan=require('../src/ammo-only-plan'),owned=require('../shared/owned-functions'),language=require('../src/game-language'),ui=require('../src/vending-ui');
test('ammo UI contains only three vending and three shop functions, not decal management',()=>{
 assert.equal(plan.patches.length,6);assert.deepEqual(plan.features,['materials','ammo']);
 assert(!plan.patches.some(p=>p.name.includes('SkillExchange')));
 assert.equal(ui.preset({decals:false,ammo:true,language:'ko'}),'ammo-ko');
 const setup=Buffer.from(plan.patches.find(p=>p.name.endsWith('SetupTopMenu')).insert,'hex');
 assert(setup.includes(Buffer.from('탄약 충전','utf16le')));assert(!setup.includes(Buffer.from('데칼 교체','utf16le')));
 const en=language.localizePlan(plan,'en');for(let i=0;i<plan.patches.length;i++){assert.equal(en.patches[i].insert.length,plan.patches[i].insert.length);assert.deepEqual(en.patches[i].jumps,plan.patches[i].jumps);}
 for(const p of plan.patches)for(const j of p.jumps)assert.equal(j.after,j.before>p.memoryAt||(p.memoryAt===0&&j.before===0)?j.before+p.extraMemory:j.before,p.name+' relocation');
});
test('ammo scope preserves arbitrary unowned Tick bytes, but default/full ownership remains strict',()=>{
 const v=owned.group('vending','BrgGame.upk',91836),unknown=Buffer.concat([v[0].off,Buffer.alloc(373)]);
 assert.equal(unknown.length,11582);assert.equal(owned.owns(v,'ammo-ko'),false);
 assert.deepEqual(owned.merge(unknown,v,'ammo-ko'),unknown);
 assert.throws(()=>owned.merge(unknown,v,'all-ko'),/conflict/);assert.throws(()=>owned.merge(unknown,v,'off'),/conflict/);
});
for(const lang of ['ko','en'])test('ammo-only generated bytecode executes complete payment/cancel/save suite: '+lang,()=>{
 const env={...process.env,LID_TEST_AMMO_ONLY:'1',LID_TEST_GAME_LANGUAGE:lang};delete env.NODE_TEST_CONTEXT;
 const r=cp.spawnSync(process.execPath,['--no-warnings','--test','--test-reporter=tap',path.join(__dirname,'ammo-bytecode.test.js')],{env,encoding:'utf8',windowsHide:true,timeout:30000});
 assert.equal(r.status,0,r.stdout+r.stderr);assert.match(r.stdout,/# pass 11/);assert.match(r.stdout,/# fail 0/);
});
